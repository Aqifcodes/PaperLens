import os
import io
import re
from html import escape
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from reportlab.lib import colors
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfbase.pdfmetrics import registerFontFamily

FONTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'fonts')

_FONTS_INITIALIZED = False


def _init_fonts():
    global _FONTS_INITIALIZED
    if _FONTS_INITIALIZED:
        return

    regular_path = os.path.join(FONTS_DIR, 'DejaVuSans.ttf')
    bold_path = os.path.join(FONTS_DIR, 'DejaVuSans-Bold.ttf')

    if os.path.exists(regular_path) and os.path.exists(bold_path):
        try:
            pdfmetrics.registerFont(TTFont('DejaVuSans', regular_path))
            pdfmetrics.registerFont(TTFont('DejaVuSans-Bold', bold_path))
            registerFontFamily('DejaVuSans', normal='DejaVuSans', bold='DejaVuSans-Bold')
        except Exception as e:
            print(f"Warning: could not register DejaVuSans fonts: {e}")
    _FONTS_INITIALIZED = True


def safe_paragraph_text(text):
    if not text:
        return ''
    escaped = escape(str(text))
    escaped = re.sub(r'\*\*(.*?)\*\*', r'<b>\1</b>', escaped)
    escaped = re.sub(r'\*(.*?)\*', r'<i>\1</i>', escaped)
    return escaped


def add_header_footer(canvas, doc):
    canvas.saveState()
    font_name = 'DejaVuSans' if 'DejaVuSans' in pdfmetrics.getRegisteredFontNames() else 'Helvetica'
    canvas.setFont(font_name, 8)
    canvas.setFillColor(colors.HexColor('#8A92A3'))
    # Header
    canvas.drawString(40, letter[1] - 25, "PaperLens Analysis Report")
    # Footer
    page_num = f"Page {doc.page}"
    canvas.drawRightString(letter[0] - 40, 25, page_num)
    canvas.drawString(40, 25, "Generated by PaperLens")
    canvas.restoreState()


def generate_pdf(data):
    _init_fonts()

    is_paper = bool(data.get('is_paper'))
    title = data.get('title') or (data.get('metadata') or {}).get('title') or 'Untitled Document'

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=40,
        rightMargin=40,
        topMargin=40,
        bottomMargin=40,
        title=f"{title} - PaperLens",
        author="PaperLens",
        subject="Document analysis"
    )

    has_dejavu = 'DejaVuSans' in pdfmetrics.getRegisteredFontNames()
    normal_font = 'DejaVuSans' if has_dejavu else 'Helvetica'
    bold_font = 'DejaVuSans-Bold' if has_dejavu else 'Helvetica-Bold'

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName=bold_font,
        fontSize=18,
        leading=22,
        textColor=colors.HexColor('#0F1117'),
        spaceAfter=4
    )
    author_style = ParagraphStyle(
        'DocAuthor',
        parent=styles['Normal'],
        fontName=normal_font,
        fontSize=9.5,
        leading=13.5,
        textColor=colors.HexColor('#8A92A3'),
        spaceAfter=8
    )
    section_head_style = ParagraphStyle(
        'DocSectionHead',
        parent=styles['Normal'],
        fontName=bold_font,
        fontSize=10.5,
        leading=14,
        textColor=colors.HexColor('#2C6BED'),
        spaceBefore=10,
        spaceAfter=4
    )
    body_style = ParagraphStyle(
        'DocBody',
        parent=styles['Normal'],
        fontName=normal_font,
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor('#2D3748'),
        spaceAfter=4
    )
    bullet_style = ParagraphStyle(
        'DocBullet',
        parent=body_style,
        leftIndent=14,
        spaceAfter=3
    )

    story = []

    story.append(Paragraph(safe_paragraph_text(title), title_style))

    if is_paper:
        authors = data.get('authors') or (data.get('metadata') or {}).get('authors') or ''
        if authors:
            story.append(Paragraph(safe_paragraph_text(authors), author_style))

    story.append(HRFlowable(
        width='100%',
        thickness=0.75,
        color=colors.HexColor('#E4E7ED'),
        spaceBefore=6,
        spaceAfter=8
    ))

    def add_content(text):
        if not text:
            story.append(Paragraph('—', body_style))
            return
        lines = [l.strip() for l in str(text).split('\n') if l.strip()]
        bullet_re = re.compile(r'^([-*•]|\d+[.)])\s+')
        for l in lines:
            cl = safe_paragraph_text(l)
            if bullet_re.match(cl):
                sub = bullet_re.sub('', cl)
                story.append(Paragraph(f'&bull;&nbsp;&nbsp;{sub}', bullet_style))
            else:
                story.append(Paragraph(cl, body_style))

    if is_paper:
        abstract = data.get('abstract') or (data.get('metadata') or {}).get('abstract') or ''
        if abstract:
            story.append(Paragraph('ABSTRACT', section_head_style))
            story.append(Paragraph(safe_paragraph_text(abstract), body_style))

        cards = [
            ('SUMMARY', data.get('summary')),
            ('METHODOLOGY', data.get('methodology')),
            ('DATASETS USED', data.get('dataset')),
            ('KEY RESULTS', data.get('results')),
            ('LIMITATIONS &amp; FUTURE WORK', data.get('limitations'))
        ]
        for name, val in cards:
            story.append(Paragraph(name, section_head_style))
            add_content(val)

    qa = data.get('qa_history') or []
    if qa or not is_paper:
        story.append(Paragraph('QUESTIONS &amp; ANSWERS', section_head_style))
        if not qa:
            story.append(Paragraph('No questions asked yet.', body_style))
        else:
            for item in qa:
                q = item.get('question', '')
                a = item.get('answer', '')
                story.append(Paragraph(f'<b>Q:</b> {safe_paragraph_text(q)}', body_style))
                add_content(a)
                story.append(Spacer(1, 4))

    doc.build(story, onFirstPage=add_header_footer, onLaterPages=add_header_footer)
    return buf.getvalue()
